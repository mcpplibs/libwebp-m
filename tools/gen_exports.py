#!/usr/bin/env python3
"""Write the modules' export lists from libwebp's public headers.

For each group of tools/inventory.py:

- the module interface exports every type, enumerator and WEBP_EXTERN function
  of the group's headers by `export using`: the upstream globals, unchanged;
- the `static WEBP_INLINE` functions (internal linkage, not exportable) are
  declared in namespace mcpplibs::mwrap::libwebp under the same names and
  signatures, and defined out of line in the group's implementation unit by
  calling upstream's own inline body.

  core      src/libwebp.cppm        src/inline.cpp
  sharpyuv  src/sharpyuv.cppm       src/sharpyuv_inline.cpp
  demux     src/demux/demux.cppm    src/demux/inline.cpp
  mux       src/mux/mux.cppm        src/mux/inline.cpp

The macros are src/macros.cppm's, written by hand (tools/check_exports.py
accounts for every one). With --check, nothing is written and a difference
fails.
"""
import argparse
from pathlib import Path
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
from inventory import INCLUDES, fetch, surface  # noqa: E402

GENERATED = '// Generated by tools/gen_exports.py from libwebp 1.5.0\'s headers — do not edit\n// by hand.\n'

MODULES = {
    'core': {
        'interface': 'src/libwebp.cppm', 'implementation': 'src/inline.cpp',
        'module': 'mcpplibs.mwrap.libwebp',
        'about': '''//
// mcpplibs.mwrap.libwebp — libwebp, the WebP image codec, as a C++ module:
// decoding (webp/decode.h), encoding (webp/encode.h), the common types
// (webp/types.h) and WebPData with the animation enums (webp/mux_types.h).
// Every exported name is the upstream global, unchanged; the root also
// re-exports the macro mappings and the sharpyuv module. The codec is
// compat.libwebp, built from the same release.
//
// The `static inline` API (internal linkage, not exportable) is adapted in
// namespace mcpplibs::mwrap::libwebp under the same names and signatures, each
// calling upstream's inline body (src/inline.cpp).
''',
        'imports': ['mcpplibs.mwrap.libwebp.macros', 'mcpplibs.mwrap.libwebp.sharpyuv'],
    },
    'sharpyuv': {
        'interface': 'src/sharpyuv.cppm', 'implementation': 'src/sharpyuv_inline.cpp',
        'module': 'mcpplibs.mwrap.libwebp.sharpyuv',
        'about': '''//
// mcpplibs.mwrap.libwebp.sharpyuv — libsharpyuv, the sharp RGB to YUV
// conversion the encoder uses (sharpyuv/sharpyuv.h, sharpyuv/sharpyuv_csp.h),
// in compat.libwebp's archive. The root module re-exports it.
//
// SharpYuvOptionsInit (static inline) is adapted in mcpplibs::mwrap::libwebp.
''',
        'imports': [],
    },
    'demux': {
        'interface': 'src/demux/demux.cppm', 'implementation': 'src/demux/inline.cpp',
        'module': 'mcpplibs.mwrap.libwebp.demux',
        'about': '''//
// mcpplibs.mwrap.libwebp.demux — libwebpdemux (webp/demux.h): the container
// parser (WebPDemuxer, frames, chunks) and WebPAnimDecoder, which renders an
// animation's frames to full canvases. With the `demux` feature, which builds
// compat.libwebp's src/demux. Import it by name: the root does not re-export
// it (mcpp's scanner admits no import under a feature test); it re-exports the
// root, as demux.h includes decode.h and mux_types.h.
//
// The `static inline` API is adapted in mcpplibs::mwrap::libwebp
// (src/demux/inline.cpp).
''',
        'imports': ['mcpplibs.mwrap.libwebp'],
    },
    'mux': {
        'interface': 'src/mux/mux.cppm', 'implementation': 'src/mux/inline.cpp',
        'module': 'mcpplibs.mwrap.libwebp.mux',
        'about': '''//
// mcpplibs.mwrap.libwebp.mux — libwebpmux (webp/mux.h): the container editor
// (WebPMux: frames, ICC/EXIF/XMP chunks, canvas and animation parameters) and
// WebPAnimEncoder, which encodes full-canvas frames into an animation. With
// the `mux` feature, which builds compat.libwebp's src/mux. Import it by name:
// the root does not re-export it; it re-exports the root, as mux.h includes
// mux_types.h and WebPAnimEncoder takes encode.h's WebPConfig and WebPPicture.
//
// The `static inline` API is adapted in mcpplibs::mwrap::libwebp
// (src/mux/inline.cpp).
''',
        'imports': ['mcpplibs.mwrap.libwebp'],
    },
}


def includes(group: str) -> str:
    return ''.join(f'#include <{name}>\n' for name in INCLUDES[group])


def interface(group: str, g) -> str:
    spec = MODULES[group]
    out = [GENERATED + spec['about'] + 'module;\n' + includes(group) + f'\nexport module {spec["module"]};\n']
    if spec['imports']:
        out.append(''.join(f'export import {name};\n' for name in spec['imports']))
    out.append(f'// types ({len(g.types)})')
    out += [f'export using ::{n};' for n in g.types]
    out.append(f'\n// enumerators ({len(g.enumerators)})')
    out += [f'export using ::{n};' for n in g.enumerators]
    out.append(f'\n// functions ({len(g.functions)})')
    out += [f'export using ::{n};' for n in g.functions]
    out.append(f'\n// the static inline API ({len(g.inline)}), adapted')
    out.append('export namespace mcpplibs::mwrap::libwebp {')
    out += [i.declaration() + ';' for i in g.inline]
    out.append('}  // namespace mcpplibs::mwrap::libwebp')
    return '\n'.join(out) + '\n'


def implementation(group: str, g) -> str:
    spec = MODULES[group]
    out = [GENERATED + '//\n// The adaptations of the static inline API of\n//\n' +
           ''.join(f'//   {name}\n' for name in INCLUDES[group]) +
           '//\n// each calling upstream\'s own inline body.\nmodule;\n' + includes(group) +
           f'\nmodule {spec["module"]};\n\nnamespace mcpplibs::mwrap::libwebp {{\n']
    out += [i.definition() for i in g.inline]
    out.append('\n}  // namespace mcpplibs::mwrap::libwebp')
    return '\n'.join(out) + '\n'


def outputs(root: Path) -> dict[str, str]:
    sf = surface(fetch(root))
    files = {}
    for group, g in sf.items():
        files[MODULES[group]['interface']] = interface(group, g)
        files[MODULES[group]['implementation']] = implementation(group, g)
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    stale = []
    for name, text in outputs(root).items():
        path = root / name
        current = path.read_text(encoding='utf-8') if path.exists() else None
        if current == text:
            continue  # unchanged files keep their timestamps
        if args.check:
            stale.append(name)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding='utf-8', newline='\n')
        print('wrote', name)
    if stale:
        sys.exit('not what tools/gen_exports.py writes: ' + ', '.join(stale))


if __name__ == '__main__':
    main()
